// Codificación legacy de contraseñas del POS (SPDB) para dbo.USUARIOS.Pasword.
// Portado del PasswordLegacyCodec del backend del compañero (BackBorradorDev).
// Cada carácter se guarda como su "contenido" (2 o 3 bytes) seguido del byte 0x3F.
// La comparación es sin distinguir mayúsculas (el carácter se pasa a minúscula).

const SEPARADOR = 0x3f;

// carácter -> bytes (sin el separador)
const TABLA = {
  '0': [0xae, 0xc5],
  '1': [0xae, 0xe6],
  '2': [0xb5, 0xa3],
  '3': [0xb5, 0xb6],
  '4': [0xb5, 0xa4],
  '5': [0xb5, 0xa2],
  '6': [0xb5, 0xae],
  '7': [0xb5, 0xb5],
  '8': [0xb5, 0xbb],
  '9': [0xb5, 0xa9],

  a: [0xe6, 0xa9],
  b: [0xe6, 0xc5],
  c: [0xe6, 0xe6],

  d: [0xb6, 0xa3, 0xa3],
  e: [0xb6, 0xa3, 0xb6],
  f: [0xb6, 0xa3, 0xa4],
  g: [0xb6, 0xa3, 0xa2],
  h: [0xb6, 0xa3, 0xae],
  i: [0xb6, 0xa3, 0xb5],
  j: [0xb6, 0xa3, 0xbb],
  k: [0xb6, 0xa3, 0xa9],
  l: [0xb6, 0xa3, 0xc5],
  m: [0xb6, 0xa3, 0xe6],

  n: [0xb6, 0xb6, 0xa3],
  o: [0xb6, 0xb6, 0xb6],
  p: [0xb6, 0xb6, 0xa4],
  q: [0xb6, 0xb6, 0xa2],
  r: [0xb6, 0xb6, 0xae],
  s: [0xb6, 0xb6, 0xb5],
  t: [0xb6, 0xb6, 0xbb],
  u: [0xb6, 0xb6, 0xa9],
  v: [0xb6, 0xb6, 0xc5],
  w: [0xb6, 0xb6, 0xe6],

  x: [0xb6, 0xa4, 0xa3],
  y: [0xb6, 0xa4, 0xb6],
  z: [0xb6, 0xa4, 0xa4],

  ' ': [0xa2, 0xa4],
  '@': [0xbb, 0xae],
  _: [0xe6, 0xb5],
  '-': [0xae, 0xb5],
  '.': [0xae, 0xbb],
};

// Codifica un texto al formato de Pasword. Devuelve un Buffer, o null si algún
// carácter no está en la tabla (para no dar un falso positivo).
function codificar(texto) {
  const bytes = [];
  for (const raw of String(texto)) {
    const contenido = TABLA[raw.toLowerCase()];
    if (!contenido) return null;
    bytes.push(...contenido, SEPARADOR);
  }
  return Buffer.from(bytes);
}

const cubreTodo = (texto) => [...String(texto)].every((c) => TABLA[c.toLowerCase()]);

module.exports = { codificar, cubreTodo, TABLA };
